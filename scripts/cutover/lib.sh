#!/usr/bin/env bash

set -euo pipefail

CUTOVER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$CUTOVER_DIR/../.." && pwd)"
COMPOSE_DIR="$REPO_ROOT/deployments/docker-compose"
STATE_DIR="$COMPOSE_DIR/.cutover"
STATE_FILE="$STATE_DIR/state.env"
OVERRIDES_DIR="$STATE_DIR/gateway"
OVERRIDES_FILE="$OVERRIDES_DIR/overrides.json"

compose() {
  docker compose \
    --project-directory "$COMPOSE_DIR" \
    -f "$COMPOSE_DIR/docker-compose.yaml" \
    -f "$COMPOSE_DIR/docker-compose.cutover.yaml" \
    --env-file "$STATE_FILE" "$@"
}

load_state() {
  if [[ ! -f "$STATE_FILE" ]]; then
    printf 'Cutover state is not initialized; run cutover.sh up first.\n' >&2
    return 1
  fi
  set -a
  # This file is generated by write_state and contains only controlled assignments.
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  set +a
}

write_state() {
  mkdir -p "$STATE_DIR"
  local temporary="$STATE_FILE.tmp"
  {
    printf 'IDENTITY_OWNER=%s\n' "$IDENTITY_OWNER"
    printf 'FLIGHT_OWNER=%s\n' "$FLIGHT_OWNER"
    printf 'PASSENGER_OWNER=%s\n' "$PASSENGER_OWNER"
    printf 'BOOKING_OWNER=%s\n' "$BOOKING_OWNER"
    printf 'IDENTITY_MONOLITH_BACKGROUND=%s\n' "$IDENTITY_MONOLITH_BACKGROUND"
    printf 'FLIGHT_MONOLITH_BACKGROUND=%s\n' "$FLIGHT_MONOLITH_BACKGROUND"
    printf 'PASSENGER_MONOLITH_BACKGROUND=%s\n' "$PASSENGER_MONOLITH_BACKGROUND"
    printf 'BOOKING_MONOLITH_BACKGROUND=%s\n' "$BOOKING_MONOLITH_BACKGROUND"
    printf 'IDENTITY_SERVICE_BACKGROUND=%s\n' "$IDENTITY_SERVICE_BACKGROUND"
    printf 'FLIGHT_SERVICE_BACKGROUND=%s\n' "$FLIGHT_SERVICE_BACKGROUND"
    printf 'PASSENGER_SERVICE_BACKGROUND=%s\n' "$PASSENGER_SERVICE_BACKGROUND"
    printf 'BOOKING_SERVICE_BACKGROUND=%s\n' "$BOOKING_SERVICE_BACKGROUND"
    printf 'FLIGHT_GRPC_ADDRESS=%s\n' "$FLIGHT_GRPC_ADDRESS"
    printf 'PASSENGER_GRPC_ADDRESS=%s\n' "$PASSENGER_GRPC_ADDRESS"
    printf 'FLIGHT_GRPC_ADDRESS_FOR_SERVICES=%s\n' "$FLIGHT_GRPC_ADDRESS_FOR_SERVICES"
    printf 'PASSENGER_GRPC_ADDRESS_FOR_SERVICES=%s\n' "$PASSENGER_GRPC_ADDRESS_FOR_SERVICES"
    printf 'MONOLITH_IMAGE=%s\n' "${MONOLITH_IMAGE:-booking-modular-monolith:legacy}"
    printf 'FLIP_IN_PROGRESS=%s\n' "${FLIP_IN_PROGRESS:-}"
  } >"$temporary"
  mv "$temporary" "$STATE_FILE"
}

owner_for() {
  case "$1" in
    identity) printf '%s' "$IDENTITY_OWNER" ;;
    flight) printf '%s' "$FLIGHT_OWNER" ;;
    passenger) printf '%s' "$PASSENGER_OWNER" ;;
    booking) printf '%s' "$BOOKING_OWNER" ;;
    *) printf 'Unknown context: %s\n' "$1" >&2; return 2 ;;
  esac
}

set_owner() {
  case "$1" in
    identity) IDENTITY_OWNER="$2" ;;
    flight) FLIGHT_OWNER="$2" ;;
    passenger) PASSENGER_OWNER="$2" ;;
    booking) BOOKING_OWNER="$2" ;;
    *) printf 'Unknown context: %s\n' "$1" >&2; return 2 ;;
  esac
}

refresh_derived_state() {
  local context owner
  for context in identity flight passenger booking; do
    owner="$(owner_for "$context")"
    printf -v "${context^^}_MONOLITH_BACKGROUND" '%s' "$([[ "$owner" == monolith ]] && printf true || printf false)"
    printf -v "${context^^}_SERVICE_BACKGROUND" '%s' "$([[ "$owner" == service ]] && printf true || printf false)"
  done
  if [[ "$FLIGHT_OWNER" == monolith ]]; then
    FLIGHT_GRPC_ADDRESS=http://monolith:81
    FLIGHT_GRPC_ADDRESS_FOR_SERVICES=http://monolith:81
  else
    FLIGHT_GRPC_ADDRESS=http://flight-service:81
    FLIGHT_GRPC_ADDRESS_FOR_SERVICES=http://flight-service:81
  fi
  if [[ "$PASSENGER_OWNER" == monolith ]]; then
    PASSENGER_GRPC_ADDRESS=http://monolith:81
    PASSENGER_GRPC_ADDRESS_FOR_SERVICES=http://monolith:81
  else
    PASSENGER_GRPC_ADDRESS=http://passenger-service:81
    PASSENGER_GRPC_ADDRESS_FOR_SERVICES=http://passenger-service:81
  fi
}

cluster_address() {
  local context="$1" owner
  owner="$(owner_for "$context")"
  if [[ "$owner" == monolith ]]; then
    printf 'http://monolith:80/'
  else
    printf 'http://%s-service:80/' "$context"
  fi
}

write_gateway_overrides() {
  local frozen="${1:-}"
  mkdir -p "$OVERRIDES_DIR"
  jq -n \
    --arg identity "$(cluster_address identity)" \
    --arg flight "$(cluster_address flight)" \
    --arg passenger "$(cluster_address passenger)" \
    --arg booking "$(cluster_address booking)" \
    --arg frozen "$frozen" \
    '{
      ReverseProxy: {
        Clusters: {
          identity: {Destinations: {primary: {Address: $identity}}},
          flight: {Destinations: {primary: {Address: $flight}}},
          passenger: {Destinations: {primary: {Address: $passenger}}},
          booking: {Destinations: {primary: {Address: $booking}}}
        }
      },
      Cutover: {
        FrozenClusters: ($frozen | split(",") | map(select(length > 0))),
        RetryAfterSeconds: 30
      }
    }' >"$OVERRIDES_FILE.tmp"
  mv "$OVERRIDES_FILE.tmp" "$OVERRIDES_FILE"
}

wait_healthy() {
  local service="$1" container status attempt
  for attempt in {1..60}; do
    container="$(compose ps -q "$service")"
    if [[ -n "$container" ]]; then
      status="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$container" 2>/dev/null || true)"
      if [[ "$status" == healthy || "$status" == running ]]; then
        return 0
      fi
    fi
    sleep 2
  done
  printf 'Timed out waiting for %s to become healthy.\n' "$service" >&2
  compose logs --tail 100 "$service" >&2 || true
  return 1
}

cutover_token() {
  local response
  response="$(curl --silent --show-error --config - <<'CURL'
url = "http://localhost:5000/connect/token"
request = "POST"
data-urlencode = "grant_type=password"
data-urlencode = "username=samh"
data-urlencode = "password=Admin@123456"
data-urlencode = "client_id=client"
data-urlencode = "client_secret=secret"
data-urlencode = "scope=flight-api passenger-api booking-api identity-api booking-modular-monolith"
CURL
)"
  jq -er '.access_token' <<<"$response"
}

gateway_probe() {
  local context="$1" token="$2" path response
  case "$context" in
    identity) path=/api/v1.0/identity ;;
    flight) path=/api/v1.0/flight ;;
    passenger) path=/api/v1.0/passenger ;;
    booking) path=/api/v1.0/booking ;;
    *) return 2 ;;
  esac
  response="$(curl --silent --show-error --dump-header - --output /dev/null --write-out '\n%{http_code}' --config - <<CURL
url = "http://localhost:5000$path"
header = "Authorization: Bearer $token"
CURL
)"
  printf '%s' "$response"
}

probe_status() {
  printf '%s\n' "$1" | tail -n 1
}

probe_frozen() {
  local context="$1" token="$2" attempt response status
  for attempt in {1..30}; do
    response="$(gateway_probe "$context" "$token")"
    status="$(probe_status "$response")"
    if [[ "$status" == 503 ]] && grep -qi '^X-Gateway-Cutover: frozen' <<<"$response"; then
      return 0
    fi
    sleep 1
  done
  printf 'Gateway did not report %s frozen; last status was %s.\n' "$context" "$status" >&2
  return 1
}

probe_routed() {
  local context="$1" address="$2" token="$3" since="$4" attempt response status
  for ((attempt = 1; attempt <= 30; attempt += 1)); do
    response="$(gateway_probe "$context" "$token")"
    status="$(probe_status "$response")"
    if [[ "$status" != 401 && "$status" != 503 ]] &&
      docker logs --since "$since" booking_gateway 2>&1 | grep -Fq "destination=$address,"; then
      return 0
    fi
    sleep 1
  done
  printf 'Gateway did not confirm routing %s to %s (last status %s).\n' "$context" "$address" "$status" >&2
  docker logs --since "$since" booking_gateway >&2 || true
  return 1
}

set_context_freeze() {
  case "$1" in
    flight) write_gateway_overrides 'flight,booking' ;;
    passenger) write_gateway_overrides 'passenger,booking' ;;
    booking) write_gateway_overrides booking ;;
    identity) write_gateway_overrides identity ;;
    *) return 2 ;;
  esac
}

clear_freeze() {
  write_gateway_overrides
}
